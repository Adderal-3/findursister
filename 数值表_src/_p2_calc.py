# -*- coding: utf-8 -*-
"""P2 道具经济平衡表 测算脚本 v2.5
口径变更(v2.5 契约):
  D11/D24 体力新经济: 在线每3分钟+1/每日补到20/体力视频+5每日计奖≤4/UGC有效完成奖励+5日限3/无尽入场5每局
  D16/D23 视频三入口: ①体力耗尽看视频+5 ②局中看视频固定加时+15s(每关≤3 满格截断) ③卡关看视频换放大镜+1
  D15 无掉队: 鸟瞰「每日签到+1」改为「每日首次通关+1」(日限1; 通过=找齐全部目标)
  D6  无尽禁用全部4种道具(正式决议)
两档玩家口径: 无视频玩家(NV) N=40关次/天(区间35~45) / 看视频玩家(V) N=65关次/天(模型55~75，运营目标60~75)
时光沙漏重定位: 「免看视频立即加时」库存道具, 与视频加时共享每关≤3次上限;
  可重复来源「每日首三星+1(日限2)」在 v2.4 移除(见 props_notes.md §一)
"""
import csv, os

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "props_economy.csv")

def f2(x):
    return f"{round(x + 1e-9, 2):.2f}"

# ---------- 两档设计中心与敏感度区间 ----------
CENTER = {"NV": 40, "V": 65}
SENS = {"NV": (35, 40, 45), "V": (60, 65, 75)}

# ---------- 获取侧参数(推进期口径) ----------
PROG_DAYS = {"NV": 35, "V": 25}        # 推进期天数: 100关+章节+刷星回炉, V档关次多推进快
FIRST3_PER_DAY = {"NV": 2.0, "V": 2.8} # 推进期日均新增「每关首次三星」数
ENDLESS_RUNS = {"NV": 1.5, "V": 2.0}   # 日均无尽局数(入场5眼力/局, 已计入两档体力预算)
FIRST_PASS_RATE = {"NV": 0.95, "V": 0.98}  # 「每日首次通关+1」达成率
MAG_VIDEO_PER_DAY = 0.30               # D16入口③ 卡关看视频换放大镜 日均次数(仅V档)
HG_VIDEO_SPLIT = 0.70                  # D16入口② 分流假设: V档70%加时需求被免费视频通道吸收
WATCH_DAILY_CAP = 3                    # 怀表每日上限(契约: 每局≤2 每日≤3)
P_W5, P_W10 = 0.9, 0.5                 # 无尽单局到达第5/10波概率

# ---------- 需求侧行为基线(与旧版一致, 随N缩放) ----------
HARD, SPEED = 0.30, 0.05               # 高难局占比(迷踪10+夜航10+Boss10) / 极速局占比

def demands(N):
    """返回 (放大镜, 沙漏, 怀表, 鸟瞰) 日需求; 沙漏为分流前总加时需求"""
    hard, speed = N * HARD, N * SPEED
    mag = hard * 0.06 + (N - hard) * 0.005      # 高难局6%需第2次提示 + 普通局0.5%
    hg = N * 0.08 * 1.15                        # 8%的局需要加时, 平均1.15次/局
    w = N * 0.30 * 0.15 + N * 0.11 * 0.18       # 刷星回炉局15% + Boss/高难冲刺局18%
    b = hard * 0.07 + speed * 0.04              # 高难迷路7% + 极速找方向4%
    return mag, hg, w, b

def gains(tier):
    """返回 (放大镜, 沙漏, 怀表, 鸟瞰) 日获取(推进期口径)"""
    pd = PROG_DAYS[tier]
    mag = 30 / pd + (MAG_VIDEO_PER_DAY if tier == "V" else 0)   # 小章+3/章共30 + D16③
    hg = FIRST3_PER_DAY[tier] + 22 / pd        # 每关首三星+1 + 一次性(Boss10+图鉴12)摊销
    w = min(ENDLESS_RUNS[tier] * (P_W5 + P_W10), WATCH_DAILY_CAP)
    b = FIRST_PASS_RATE[tier] + 6 / pd         # 每日首通+1(D15) + 主题集齐6个摊销
    return mag, hg, w, b

def tier_demands(tier, N):
    mag, hg, w, b = demands(N)
    if tier == "V":
        hg *= (1 - HG_VIDEO_SPLIT)             # 视频通道分流后, 落到沙漏存量的需求
    return mag, hg, w, b

# ---------- 计算与打印 ----------
NAMES = ("放大镜", "时光沙漏", "冻结怀表", "鸟瞰眼镜")
calc = {}
for tier in ("NV", "V"):
    g = gains(tier)
    calc[tier] = {}
    for N in SENS[tier]:
        d = tier_demands(tier, N)
        calc[tier][N] = (g, d)
        tag = "无视频" if tier == "NV" else "看视频"
        print(f"[{tag} N={N}] " + " | ".join(
            f"{n} {g[i]:.2f}/{d[i]:.2f}={g[i]/d[i]:.0%}" for i, n in enumerate(NAMES)))

g_nv, d_nv = calc["NV"][CENTER["NV"]]
g_v, d_v = calc["V"][CENTER["V"]]

rows = [
    ["道具", "效果", "每关使用上限", "获取途径",
     "日获取量预估(无视频玩家)", "日获取量预估(看视频玩家)",
     "日消耗量预估(无视频玩家)", "日消耗量预估(看视频玩家)",
     "存量上限", "反滥用规则"],
    ["放大镜",
     "闪烁高亮一个未找到的目标并镜头自动移过去",
     "3次（含每局免费1次）",
     "每局免费1次（不计存量）；小章通关奖励+3个（10小章共30个一次性）；卡关时看30s站内视频换+1（D16入口③）",
     f2(g_nv[0]), f2(g_v[0]), f2(d_nv[0]), f2(d_v[0]), "10",
     "免费次数当局有效不结转下局；同一目标已被高亮后不重复消耗次数；无尽模式禁用（D6正式决议）"],
    ["时光沙漏",
     "免看视频立即加时：剩余时间固定+15秒（与视频加时同值 满格截断）",
     "3次（与视频加时入口合计）",
     "每关首次三星+1（全周期共100个一次性）；Boss关首通必掉+1（共10个）；图鉴每集齐1主题+2（共12个）",
     f2(g_nv[1]), f2(g_v[1]), f2(d_nv[1]), f2(d_v[1]), "10",
     "视频加时与沙漏合计每关≤3次；加时后超本关总时长截断 剩余时间满格时沙漏与视频加时两个入口都置灰；每关首次三星奖励按关卡ID终身一次 重复刷不重复给；无尽模式禁用（D6正式决议）"],
    ["冻结怀表",
     "计时冻结5秒（冻结期间点错仍扣3秒）",
     "1次",
     "无尽模式第5波与第10波各+1（每局上限2个 每日上限3个；通关第60关解锁无尽）",
     f2(g_nv[2]), f2(g_v[2]), f2(d_nv[2]), f2(d_v[2]), "5",
     "冻结只暂停自然计时不豁免点错惩罚；按波次里程碑结算 中途超时按已达波次发放；无尽模式内禁用（D6正式决议 获得渠道与使用场景分离）"],
    ["鸟瞰眼镜",
     "镜头拉远展示全场景2秒（展示期间计时照常且点击锁定）",
     "1次",
     "图鉴集齐2主题后解锁资格；解锁后每日首次通关+1（日限1 D15对齐 通过=找齐全部目标）；图鉴每集齐1主题一次性+1（共6个）",
     f2(g_nv[3]), f2(g_v[3]), f2(d_nv[3]), f2(d_v[3]), "5",
     "展示期间点击锁定且计时不暂停（不构成免费暂停）；每日首通奖励日限1当日重置；主题集齐奖励一次性按主题ID记录；无尽模式禁用（D6正式决议）"],
]
with open(OUT, "w", encoding="utf-8", newline="") as fp:
    csv.writer(fp).writerows(rows)
print("written:", OUT, "rows:", len(rows))
